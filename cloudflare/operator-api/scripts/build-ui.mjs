#!/usr/bin/env node
/** Deterministic text bundle, avoiding the Static Assets router so ctx.access
 * remains available. No network downloads. Uses the installed TypeScript compiler.
 */
import {readFileSync,writeFileSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../',import.meta.url));
const check=process.argv.includes('--check');
if(process.argv.slice(2).some(a=>a!=='--check'))throw Error('Usage: node build-ui.mjs [--check]');
const tmp=mkdtempSync(join(tmpdir(),'africlub-ui-build-'));
try{
 execFileSync('tsc',[join(root,'client.ts'),'--strict','--target','ES2022','--module','ES2022','--lib','ES2022,DOM','--outDir',tmp],{stdio:'pipe'});
 const caseOut=join(tmp,'case');
 execFileSync('tsc',[join(root,'../payment-exceptions/client.ts'),'--strict','--target','ES2022','--module','ES2022','--lib','ES2022,DOM','--outDir',caseOut],{stdio:'pipe'});
 const tokens=fileURLToPath(new URL('../../../apps/rayon_sports/web/src/ui-kit/tokens.css',import.meta.url));
 const text=p=>readFileSync(p,'utf8');
 const sources={
  'client.ts':text(join(root,'client.ts')),'ui/controller.mjs':text(join(root,'ui/controller.mjs')),
  'ui/app.mjs':text(join(root,'ui/app.mjs')),'ui/page.html':text(join(root,'ui/page.html')),
  'ui/cases.html':text(join(root,'ui/cases.html')), 'ui/cases.mjs':text(join(root,'ui/cases.mjs')),
  'ui/case-controller.mjs':text(join(root,'ui/case-controller.mjs')), '../payment-exceptions/client.ts':text(join(root,'../payment-exceptions/client.ts')),
  'ui/styles.css':text(join(root,'ui/styles.css')),'shared-ui-tokens':text(tokens),
 };
 const assets={'client.js':text(join(tmp,'client.js')),'controller.js':sources['ui/controller.mjs'],
  'case-client.js':text(join(caseOut,'client.js')), 'case-controller.js':sources['ui/case-controller.mjs'], 'cases.js':sources['ui/cases.mjs'],
  'app.js':sources['ui/app.mjs'],'styles.css':sources['shared-ui-tokens']+'\n'+sources['ui/styles.css']};
 const hashes=Object.fromEntries(Object.entries(sources).map(([p,s])=>[p,createHash('sha256').update(s).digest('hex')]));
 const output='// Generated by scripts/build-ui.mjs. Edit ui/* or client.ts, then rebuild.\n'+
  'export const UI_SOURCE_HASHES='+JSON.stringify(hashes,null,2)+';\n'+
  'export const CASES_HTML='+JSON.stringify(sources['ui/cases.html'])+';\n'+
  'export const UI_HTML='+JSON.stringify(sources['ui/page.html'])+';\n'+
  'export const UI_ASSETS=Object.freeze('+JSON.stringify(assets,null,2)+');\n';
 const destination=join(root,'src/ui-assets.mjs');
 if(check){if(readFileSync(destination,'utf8')!==output)throw Error('UI bundle differs from its sources. Run build-ui.mjs.');}
 else writeFileSync(destination,output);
 console.log(check?'UI bundle source parity passed.':'UI bundle regenerated without Static Assets.');
}finally{rmSync(tmp,{recursive:true,force:true});}
