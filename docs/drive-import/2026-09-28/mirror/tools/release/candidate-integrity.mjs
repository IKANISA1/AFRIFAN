#!/usr/bin/env node
import {createHash, createPublicKey, verify} from 'node:crypto';
import {readFileSync, readdirSync, lstatSync, realpathSync, writeFileSync} from 'node:fs';
import {resolve, relative, sep} from 'node:path';
import {pathToFileURL} from 'node:url';

const HASH=/^[a-f0-9]{64}$/, COMMIT=/^[a-f0-9]{40}$/;
const roles=['security','operations','product','privacy'];
const exact=(v,keys)=>v&&typeof v==='object'&&!Array.isArray(v)&&Object.keys(v).length===keys.length&&keys.every(k=>Object.hasOwn(v,k));
const guard=(v,why)=>{if(!v)throw new Error(why);};
export const digest=b=>createHash('sha256').update(b).digest('hex');
const sensitive=/(^|\/)(?:\.env(?!\.example$)[^/]*|\.dev\.vars(?!\.example$)[^/]*|keystore\.properties|[^/]+\.(?:jks|p12|pfx|pem|key)|id_rsa|id_ed25519|credentials\.json|service-account[^/]*\.json)$/i;
export function inventory(root) {
  root=resolve(root);guard(lstatSync(root).isDirectory()&&!lstatSync(root).isSymbolicLink(),'artifact_root_invalid');
  guard(realpathSync(root)===root,'artifact_root_alias');
  const files=[],names=new Set();let bytes=0;
  function visit(dir){for(const e of readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name,'en'))){
    const p=resolve(dir,e.name),rel=relative(root,p).split(sep).join('/'),s=lstatSync(p);
    guard(!rel.startsWith('../')&&!rel.startsWith('/')&&!rel.includes('\\')&&!/[\x00-\x1f\x7f]/.test(rel),'artifact_path_invalid');
    guard(!s.isSymbolicLink(),'artifact_symlink');
    if(s.isDirectory()){guard(e.name!=='.git','artifact_unexpected_directory');visit(p);continue;}
    guard(s.isFile()&&s.nlink===1,'artifact_not_regular');guard(!sensitive.test(rel),'artifact_sensitive_filename');
    guard(s.size<=128*1024*1024,'artifact_file_too_large');
    const key=rel.normalize('NFC').toLowerCase();guard(!names.has(key),'artifact_name_collision');names.add(key);
    const b=readFileSync(p);guard(b.length===s.size,'artifact_changed_while_reading');
    guard(!/-----BEGIN (?:[A-Z0-9 ]+ )?PRIVATE KEY-----/.test(b.toString('utf8')),'artifact_private_key');
    files.push({path:rel,bytes:b.length,sha256:digest(b)});bytes+=b.length;
    guard(files.length<=10000&&bytes<=1024*1024*1024,'artifact_capacity');
  }}visit(root);guard(files.length>0,'artifact_empty');return files.sort((a,b)=>a.path<b.path?-1:a.path>b.path?1:0);
}
function envelope(files,commit){return {schemaVersion:1,candidateCommit:commit,files};}
export function sealArtifact(root,commit){guard(COMMIT.test(commit),'candidate_commit_invalid');const body=envelope(inventory(root),commit);return {...body,artifactDigest:digest(JSON.stringify(body))};}
export function verifyArtifact(root,manifest,expectedCommit,expectedDigest){
 guard(exact(manifest,['schemaVersion','candidateCommit','files','artifactDigest'])&&manifest.schemaVersion===1,'artifact_manifest_invalid');
 guard(COMMIT.test(expectedCommit)&&HASH.test(expectedDigest),'trusted_artifact_identity_required');
 guard(manifest.candidateCommit===expectedCommit&&manifest.artifactDigest===expectedDigest,'artifact_identity_mismatch');
 const actual=sealArtifact(root,expectedCommit);guard(actual.artifactDigest===expectedDigest&&JSON.stringify(actual.files)===JSON.stringify(manifest.files),'artifact_contents_mismatch');
 return {verified:true,candidateCommit:expectedCommit,artifactDigest:expectedDigest,fileCount:actual.files.length};
}
/** Public keys MUST come from the protected deployment environment, not from the
 * artifact, pull request, or the approval envelope. No signing key is generated by this CLI. */
export function verifyApprovals(approvals,trustedKeys,commit,artifactDigest,{now=Date.now(),environment='production'}={}){
 guard(COMMIT.test(commit)&&HASH.test(artifactDigest)&&Number.isSafeInteger(now),'approval_context_invalid');
 guard(exact(approvals,['schemaVersion','approvals'])&&approvals.schemaVersion===1&&Array.isArray(approvals.approvals)&&approvals.approvals.length===roles.length,'approvals_incomplete');
 guard(Array.isArray(trustedKeys)&&trustedKeys.length>=roles.length&&trustedKeys.length<=32,'trusted_keys_required');
 const keys=new Map();for(const k of trustedKeys){
  guard(exact(k,['keyId','role','publicKeyPem','revoked'])&&typeof k.keyId==='string'&&/^[a-zA-Z0-9_-]{3,80}$/.test(k.keyId)&&roles.includes(k.role)&&typeof k.publicKeyPem==='string'&&k.publicKeyPem.length<4096&&typeof k.revoked==='boolean'&&!keys.has(k.keyId),'trusted_key_invalid');keys.set(k.keyId,k);
 }
 const accepted=new Set(),signers=new Set(),publicKeys=new Set();
 for(const a of approvals.approvals){
  guard(exact(a,['payload','signature'])&&exact(a.payload,['schemaVersion','candidateCommit','artifactDigest','environment','role','keyId','issuedAt','expiresAt']),'approval_invalid');
  const p=a.payload,k=keys.get(p.keyId);
  guard(k&&!k.revoked&&roles.includes(p.role)&&k.role===p.role&&!accepted.has(p.role)&&!signers.has(p.keyId),'approval_identity_invalid');
  guard(p.schemaVersion===1&&p.candidateCommit===commit&&p.artifactDigest===artifactDigest&&p.environment===environment,'approval_target_mismatch');
  guard(Number.isSafeInteger(p.issuedAt)&&Number.isSafeInteger(p.expiresAt)&&p.issuedAt<=now&&p.expiresAt>now&&p.expiresAt>p.issuedAt&&p.expiresAt-p.issuedAt<=86400000,'approval_expired_or_invalid');
  guard(typeof a.signature==='string'&&/^[A-Za-z0-9+/]{86}==$/.test(a.signature),'approval_signature_invalid');
  const key=createPublicKey(k.publicKeyPem);guard(key.asymmetricKeyType==='ed25519','approval_key_algorithm');
  const fingerprint=digest(key.export({type:'spki',format:'der'}));guard(!publicKeys.has(fingerprint),'approval_signers_must_be_distinct');
  guard(verify(null,Buffer.from(JSON.stringify(p)),key,Buffer.from(a.signature,'base64')),'approval_signature_invalid');
  accepted.add(p.role);signers.add(p.keyId);publicKeys.add(fingerprint);
 }
 guard(roles.every(r=>accepted.has(r)),'approvals_incomplete');return {approved:true,roles:[...accepted],candidateCommit:commit,artifactDigest,environment};
}
if(import.meta.url===pathToFileURL(process.argv[1]??'').href){
 try{
  const [mode,root,manifestPath,commit,expectedDigest]=process.argv.slice(2);
  guard(['seal','verify','approve'].includes(mode)&&process.argv.length===(mode==='seal'?6:7),'usage: seal ROOT MANIFEST COMMIT | verify ROOT MANIFEST COMMIT DIGEST | approve APPROVALS TRUSTED_KEYS COMMIT DIGEST');
  if(mode==='seal'){const m=sealArtifact(root,commit);writeFileSync(manifestPath,JSON.stringify(m,null,2)+'\n',{flag:'wx',mode:0o600});console.log(m.artifactDigest);}
  else if(mode==='verify')console.log(JSON.stringify(verifyArtifact(root,JSON.parse(readFileSync(manifestPath)),commit,expectedDigest)));
  else console.log(JSON.stringify(verifyApprovals(JSON.parse(readFileSync(root)),JSON.parse(readFileSync(manifestPath)),commit,expectedDigest)));
 }catch(e){console.error(e.message);process.exitCode=1;}
}
