  const locales = <Locale>[Locale('en')];

  test('ships complete English task-copy catalogs', () {
    for (final locale in locales) {
      final l10n = lookupAfriLocalizations(locale);
      final taskMessages = <String>[
        l10n.genericError,
        l10n.retry,
        l10n.connectionRequired,
        l10n.onboardingBelongTitle,
        l10n.onboardingBelongBody('Rayon Sports FC'),
        l10n.onboardingKnowTitle,
        l10n.onboardingKnowBody('Gikundiro'),
        l10n.onboardingLiveTitle('Gikundiro'),
        l10n.onboardingLiveBody,
        l10n.onboardingContinueWhatsApp,
        l10n.onboardingContinueWithoutSignIn,
        l10n.onboardingWelcomeImage(1, 3),
        l10n.supportUnavailable,
        l10n.predictLineupsEmpty,
        l10n.predictStatsEmpty,
        l10n.fanIdVerifyPrompt,
        l10n.fanIdPrivacyTrust,
        ..._onboardingAuthMessages(l10n),
        ..._searchMessages(l10n),
        ..._membershipMessages(l10n),
        ..._clubMessages(l10n),
        ..._homeMessages(l10n),
        ..._fanClubMessages(l10n),
        ..._liveMessages(l10n),
        ..._shopMessages(l10n),
        ..._ticketMessages(l10n),
        ..._contributionsMessages(l10n),
        ..._settingsMessages(l10n),
        ..._adminMessages(l10n),
        ..._gameMessages(l10n),
      ];

      expect(
        taskMessages,
        everyElement(isNot(isEmpty)),
        reason: 'Every ${locale.languageCode} task message must be populated.',
      );
    }
  });

  test('the shipped catalog supports English only', () {
    expect(AfriLocalizations.supportedLocales, const <Locale>[Locale('en')]);
    expect(AfriLocalizations.delegate.isSupported(const Locale('en')), isTrue);
    expect(AfriLocalizations.delegate.isSupported(const Locale('zz')), isFalse);
  });

  test('task recovery messages stay within governed copy bounds', () {
    for (final locale in locales) {
      final l10n = lookupAfriLocalizations(locale);
      final compactMessages = <String>[
        l10n.onboardingContinueWhatsApp,
        l10n.onboardingContinueWithoutSignIn,
        l10n.fanIdVerifyPrompt,
        l10n.fanIdPrivacyTrust,
        ..._searchMessages(l10n),
      ];
      expect(
        compactMessages,
        everyElement(hasLength(lessThanOrEqualTo(100))),
        reason: '${locale.languageCode} compact copy exceeded 100 characters.',
      );
    }
  });

  test('English ARB catalogs reject duplicate top-level keys', () {
    final topLevelKey = RegExp(r'^  "([^"]+)"\s*:', multiLine: true);

    for (final language in const <String>['en']) {
      final source = _arbCatalog(language).readAsStringSync();
      final seen = <String>{};
      final duplicates = <String>{};
      for (final match in topLevelKey.allMatches(source)) {
        final key = match.group(1)!;
        if (!seen.add(key)) duplicates.add(key);
      }

      expect(
        duplicates,
        isEmpty,
        reason:
            'afri_$language.arb must not rely on order-dependent duplicate '
            'message IDs.',
      );
    }
  });

  test('Settings English ARB catalogs have exhaustive key parity', () {
    final catalogs = <String, Map<String, dynamic>>{
      for (final language in <String>['en'])
        language:
            jsonDecode(_arbCatalog(language).readAsStringSync())
                as Map<String, dynamic>,
    };
    final settingsKeys = catalogs['en']!.keys
        .where(
          (key) =>
              !key.startsWith('@') &&
              (key.startsWith('settings') ||
                  key.startsWith('editProfile') ||
                  key.startsWith('notificationPreferences') ||
                  key.startsWith('privacySettings')),
        )
        .toSet();

    expect(settingsKeys, isNotEmpty);
    for (final entry in catalogs.entries) {
      final localeKeys = entry.value.keys
          .where((key) => !key.startsWith('@'))
          .toSet();
      expect(
        localeKeys,
        containsAll(settingsKeys),
        reason: '${entry.key} must contain every Settings catalog key.',
      );
      for (final key in settingsKeys) {
        expect(
          entry.value[key],
          isA<String>().having(
            (value) => value.trim(),
            '$key translation',
            isNotEmpty,
          ),
          reason: '${entry.key} must populate $key.',
        );
      }
    }
  });

  test('Admin English ARB catalogs have exhaustive key parity', () {
    final catalogs = <String, Map<String, dynamic>>{
      for (final language in <String>['en'])
        language:
            jsonDecode(_arbCatalog(language).readAsStringSync())
                as Map<String, dynamic>,
    };
    final adminKeys = catalogs['en']!.keys
        .where((key) => !key.startsWith('@') && key.startsWith('admin'))
        .toSet();

    expect(adminKeys, isNotEmpty);
    for (final entry in catalogs.entries) {
      final localeKeys = entry.value.keys
          .where((key) => !key.startsWith('@'))
          .toSet();
      expect(
        localeKeys,
        containsAll(adminKeys),
        reason: '${entry.key} must contain every Admin catalog key.',
      );
      for (final key in adminKeys) {
        expect(
          entry.value[key],
          isA<String>().having(
            (value) => value.trim(),
            '$key translation',
            isNotEmpty,
          ),
          reason: '${entry.key} must populate $key.',
        );
      }
    }
  });

  test('football feature English catalogs have key parity', () {
    final catalogs = <String, Map<String, dynamic>>{
      for (final language in <String>['en'])
        language:
            jsonDecode(_arbCatalog(language).readAsStringSync())
                as Map<String, dynamic>,
    };
    // This pre-split namespace now contains only football, club, prediction,
    // rewards, and supporter copy. The repository boundary scanner
    // independently rejects unsupported product surfaces from every locale.
    final footballFeatureKeys = catalogs['en']!.keys
        .where((key) => !key.startsWith('@') && key.startsWith('game'))
        .toSet();

    expect(footballFeatureKeys, isNotEmpty);
    for (final entry in catalogs.entries) {
      final localeKeys = entry.value.keys
          .where((key) => !key.startsWith('@'))
          .toSet();
      expect(
        localeKeys,
        containsAll(footballFeatureKeys),
        reason: '${entry.key} must contain every football feature key.',
      );
      for (final key in footballFeatureKeys) {
        expect(
          entry.value[key],
          isA<String>().having(
            (value) => value.trim(),
            '$key translation',
            isNotEmpty,
          ),
          reason: '${entry.key} must populate $key.',
        );
      }
    }
  });

  testWidgets(
    'app and framework remain English with an unsupported stored locale',
    (tester) async {
      await tester.pumpWidget(
        MaterialApp(
          locale: const Locale('en'),
          supportedLocales: const <Locale>[Locale('en')],
          localizationsDelegates: const <LocalizationsDelegate<dynamic>>[
            AfriLocalizations.delegate,
            GlobalMaterialLocalizations.delegate,
            GlobalWidgetsLocalizations.delegate,
            GlobalCupertinoLocalizations.delegate,
          ],
          builder: (context, child) => AfriLocalizationsScope(
            locale: const Locale('zz'),
            child: child ?? const SizedBox.shrink(),
          ),
          home: Builder(
            builder: (context) => Text(
              '${Localizations.localeOf(context).languageCode}:'
              '${context.afriL10n.onboardingContinueWhatsApp}:'
              '${MaterialLocalizations.of(context).okButtonLabel}',
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();

      expect(find.textContaining('en:Continue with WhatsApp:'), findsOneWidget);
      expect(tester.takeException(), isNull);
    },
  );
}

File _arbCatalog(String language) {
  var candidate = Directory.current.absolute;
  while (candidate.parent.path != candidate.path) {
    final packageLocal = File('${candidate.path}/lib/l10n/afri_$language.arb');
    if (packageLocal.existsSync()) return packageLocal;

    final workspaceLocal = File(
      '${candidate.path}/packages/core/core_l10n/lib/l10n/'
      'afri_$language.arb',
    );
    if (workspaceLocal.existsSync()) return workspaceLocal;
    candidate = candidate.parent;
  }
  throw StateError(
    'Could not locate the core_l10n ARB catalog from ${Directory.current.path}.',
  );
}

