-- ============================================================================
-- CMS Multi-Tenant Scope
-- ============================================================================
-- Adds club-scoped CMS content and club-scoped runtime config while keeping
-- the existing public.app_config table as the global fallback layer.

CREATE TABLE IF NOT EXISTS public.home_banners (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id     bigint REFERENCES public.african_football_clubs(id),
  title       text NOT NULL DEFAULT '',
  subtitle    text NOT NULL DEFAULT '',
  badge_label text,
  cta_label   text,
  route       text NOT NULL DEFAULT '/',
  image_url   text,
  sort_order  integer NOT NULL DEFAULT 0,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.ai_content (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id      bigint REFERENCES public.african_football_clubs(id),
  content_type text NOT NULL DEFAULT 'general',
  title        text NOT NULL DEFAULT '',
  subtitle     text,
  body         text,
  rationale    text,
  icon_emoji   text,
  cta_action   text,
  cta_label    text,
  sort_order   integer NOT NULL DEFAULT 0,
  is_active    boolean NOT NULL DEFAULT true,
  status       text NOT NULL DEFAULT 'draft',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.club_app_config (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id     bigint NOT NULL REFERENCES public.african_football_clubs(id) ON DELETE CASCADE,
  key         text NOT NULL,
  value       text NOT NULL DEFAULT '',
  description text,
  country     text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE IF EXISTS public.home_banners
  ADD COLUMN IF NOT EXISTS club_id bigint REFERENCES public.african_football_clubs(id),
  ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

ALTER TABLE IF EXISTS public.ai_content
  ADD COLUMN IF NOT EXISTS club_id bigint REFERENCES public.african_football_clubs(id),
  ADD COLUMN IF NOT EXISTS rationale text,
  ADD COLUMN IF NOT EXISTS icon_emoji text,
  ADD COLUMN IF NOT EXISTS cta_action text,
  ADD COLUMN IF NOT EXISTS cta_label text,
  ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS idx_club_app_config_club_key
  ON public.club_app_config (club_id, key);

CREATE INDEX IF NOT EXISTS idx_home_banners_club_sort
  ON public.home_banners (club_id, sort_order);

CREATE INDEX IF NOT EXISTS idx_ai_content_club_type_sort
  ON public.ai_content (club_id, content_type, sort_order);

DROP TRIGGER IF EXISTS trg_home_banners_updated_at ON public.home_banners;
CREATE TRIGGER trg_home_banners_updated_at
  BEFORE UPDATE ON public.home_banners
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_ai_content_updated_at ON public.ai_content;
CREATE TRIGGER trg_ai_content_updated_at
  BEFORE UPDATE ON public.ai_content
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_club_app_config_updated_at ON public.club_app_config;
CREATE TRIGGER trg_club_app_config_updated_at
  BEFORE UPDATE ON public.club_app_config
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.club_app_config ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS club_app_config_select_scoped ON public.club_app_config;
CREATE POLICY club_app_config_select_scoped
  ON public.club_app_config FOR SELECT
  USING (
    club_id::text = COALESCE(
      (auth.jwt() -> 'app_metadata' ->> 'club_id'),
      (auth.jwt() ->> 'club_id')
    )
  );

DO $$
DECLARE
  v_default_club_id bigint;
BEGIN
  SELECT id
    INTO v_default_club_id
    FROM public.african_football_clubs
   WHERE club_slug = 'rayon_sports_rw'
   LIMIT 1;

  IF v_default_club_id IS NULL THEN
    v_default_club_id := 24;
  END IF;

  UPDATE public.home_banners
     SET club_id = v_default_club_id
   WHERE club_id IS NULL;

  UPDATE public.ai_content
     SET club_id = v_default_club_id
   WHERE club_id IS NULL;

  INSERT INTO public.club_app_config (club_id, key, value, description, country)
  SELECT
    v_default_club_id,
    config.key,
    config.value,
    config.description,
    config.country
  FROM public.app_config AS config
  ON CONFLICT (club_id, key) DO NOTHING;
END;
$$;
