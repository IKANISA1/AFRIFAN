#!/usr/bin/env python3
"""Compile the shared crest register for Flutter and the static web bundle.

Run from any directory. No network calls or generated artwork. Asset hashes are
checked before copying the same published bytes to each platform's bundle.
"""
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'packages/core/core_theme/assets'
WEB = ROOT / 'apps/rayon_sports/web'
document = json.loads((SOURCE / 'team-assets.json').read_text())
teams = document['teams']
destination = WEB / 'public/crests'
destination.mkdir(parents=True, exist_ok=True)
for team in teams:
    if not team['asset']:
        continue
    asset = SOURCE / 'crests' / team['asset']
    assert hashlib.sha256(asset.read_bytes()).hexdigest() == team['sha256'], asset
    shutil.copyfile(asset, destination / team['asset'])

sources = ['# Published team crests', '',
           'Generated from `../team-assets.json`. The same checked bytes are bundled in Flutter and web.',
           'Rights review required for release; publication provenance is recorded, not owner acceptance.', '']
for team in teams:
    if team['asset']:
        sources.extend([f'## `{team["asset"]}`', '', f'- Identity: {team["name"]}',
                        f'- source: `{team["source"]}`', f'- SHA-256: `{team["sha256"]}`', ''])
(SOURCE / 'crests/SOURCES.md').write_text('\n'.join(sources))
(destination / 'SOURCES.md').write_text('\n'.join(sources))

# Only exact aliases resolve; a partial match must never borrow a team's crest.
groups = {}
for index, team in enumerate(teams):
    for alias in [team['id'], team['slug'], team['name'], team['initials'], *team['aliases']]:
        key = re.sub('[^a-z0-9]', '', alias.lower())
        groups.setdefault(key, set()).add(index)
aliases = {key: next(iter(indices)) for key, indices in groups.items() if len(indices) == 1}
compact = [{key: row[key] for key in ['name', 'initials', 'asset']} for row in teams]
(WEB / 'src/lib/team-assets.generated.json').write_text(json.dumps({'teams': compact, 'aliases': aliases}, indent=2, ensure_ascii=False) + '\n')

def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

lines = ['// Generated by tools/scripts/sync_team_assets.py; edit assets/team-assets.json.',
         'class TeamAsset {', '  const TeamAsset(this.name, this.initials, this.asset);',
         '  final String name, initials;', '  final String? asset;', '}',
         'const teamAssets = <TeamAsset>[']
for row in compact:
    asset = dart('packages/core_theme/assets/crests/' + row['asset']) if row['asset'] else 'null'
    lines.append(f'  TeamAsset({dart(row["name"])}, {dart(row["initials"])}, {asset}),')
lines.extend(['];', 'const teamAssetAliases = <String, int>{'])
lines.extend(f'  {dart(key)}: {index},' for key, index in sorted(aliases.items()))
lines.append('};')
(ROOT / 'packages/core/core_theme/lib/src/team_assets.g.dart').write_text('\n'.join(lines) + '\n')
subprocess.run(['dart', 'format', str(ROOT / 'packages/core/core_theme/lib/src/team_assets.g.dart')], check=True, stdout=subprocess.DEVNULL)
print(f'{len(teams)} team records; {sum(bool(t["asset"]) for t in teams)} published crest assets; {len(aliases)} unambiguous aliases.')
